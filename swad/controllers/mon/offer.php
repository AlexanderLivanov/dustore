require_once __DIR__ . '/lib.php';

function mon_offer_html(string $type): string
{
    $fee = sprintf('от %d%% до %d%%', MON_FEE_MIN, MON_FEE_MAX);
    $free = number_format(MON_FEE_FREE_UPTO, 0, ',', ' ');
    $bonus = MON_BONUS_START;
    $v = MON_OFFER_VERSION;

    $settle = $type === 'npd'
        ? '<p>4.1. Разработчик применяет специальный налоговый режим «Налог на профессиональный доход». Оплаты покупателей принимаются Платформой через её платёжного агрегатора.</p>
           <p>4.2. Платформа перечисляет Разработчику полученные за его игры суммы на банковский счёт из анкеты не реже одного раза в календарный месяц, до 15 числа месяца, следующего за отчётным.</p>
           <p>4.3. Разработчик самостоятельно формирует чеки в приложении «Мой налог» на суммы, полученные от Платформы, и уплачивает налог.</p>'
        : '<p>4.1. Оплаты покупателей поступают напрямую на счёт Разработчика через выбранного им платёжного агрегатора (ЮKassa, Т-Касса и других, доступных в консоли). Платформа не является получателем этих денежных средств и не принимает их на свой счёт.</p>
           <p>4.2. Разработчик предоставляет Платформе ключи доступа к API агрегатора. Платформа использует их только для создания платежей за игры Разработчика и проверки их статуса, хранит в зашифрованном виде и не передаёт третьим лицам.</p>
           <p>4.3. Разработчик самостоятельно формирует кассовые чеки по 54-ФЗ (через агрегатора или собственную кассу), уплачивает налоги и несёт ответственность перед покупателями как продавец.</p>';

    return <<<HTML
<h3>Договор-оферта о монетизации игр на платформе Dustore</h3>
<p class="mon-offer-meta">Редакция {$v} · г. Москва</p>

<p>Индивидуальный предприниматель Ливанов Александр Алексеевич (ИНН 771392840109, ОГРНИП 326774600034839), далее «Платформа», предлагает лицу, заполнившему анкету монетизации в консоли разработчика dustore.ru, далее «Разработчик», заключить договор на условиях ниже. Договор дополняет Соглашение с разработчиком и в части расчётов имеет приоритет над ним.</p>

<h4>1. Термины</h4>
<p><b>Витрина</b> — сайт dustore.ru и приложения Платформы, где покупатели приобретают игры. <b>Агрегатор</b> — платёжный сервис, через который принимаются оплаты. <b>Инфраструктурный сбор</b> — плата Платформе за витрину, хранение и доставку игр, обработку платежей. <b>Виртуальный счёт</b> — учётный баланс Разработчика в консоли, из которого списывается сбор.</p>

<h4>2. Предмет</h4>
<p>2.1. Платформа предоставляет Разработчику витрину и техническую инфраструктуру для продажи его игр, а Разработчик оплачивает инфраструктурный сбор.</p>
<p>2.2. Права на игры остаются у Разработчика. Разработчик гарантирует, что обладает правами на продаваемые игры и материалы.</p>

<h4>3. Подключение и изменения</h4>
<p>3.1. Разработчик заполняет анкету: форму (ИП, ООО, самозанятость), данные, систему налогообложения и банковские реквизиты. Платформа проверяет данные и включает приём платежей.</p>
<p>3.2. Изменения реквизитов вступают в силу после проверки Платформой. История изменений хранится.</p>
<p>3.3. Разработчик отвечает за достоверность данных. Недостоверные данные — основание для отказа в подключении или приостановки приёма платежей.</p>

<h4>4. Расчёты с покупателями</h4>
{$settle}

<h4>5. Инфраструктурный сбор</h4>
<p>5.1. Ставку сбора Разработчик выбирает в консоли {$fee} от цены игры. Сбор списывается с виртуального счёта при каждой оплаченной покупке.</p>
<p>5.2. Разработчик выбирает, кто оплачивает сбор: покупатель (сбор прибавляется к цене) или Разработчик (цена не меняется). По желанию Разработчика к цене также прибавляется надбавка на его налог.</p>
<p>5.3. Пока доход Разработчика на Платформе за календарный месяц меньше {$free} ₽, сбор можно отключить. Когда доход за месяц достигает этой суммы, сбор применяется к последующим покупкам до конца месяца.</p>
<p>5.4. При подключении на виртуальный счёт начисляется бонус {$bonus} ₽. Бонус расходуется на сбор первым, не выводится и не возвращается.</p>
<p>5.5. Разработчик пополняет виртуальный счёт оплатой на счёт Платформы. Если средств для сбора недостаточно, продажи игр Разработчика приостанавливаются до пополнения.</p>
<p>5.6. При расторжении договора неизрасходованный остаток пополнений (без бонуса) возвращается Разработчику по его заявлению в течение 30 дней.</p>

<h4>6. Возвраты покупателям</h4>
<p>Возвраты осуществляются по правилам агрегатора и законодательству о защите прав потребителей. Сбор по возвращённой покупке возвращается на виртуальный счёт по заявлению Разработчика.</p>

<h4>7. Персональные данные</h4>
<p>Разработчик даёт согласие на обработку указанных в анкете персональных данных (ФИО, ИНН, ОГРНИП, контакты, реквизиты) для исполнения договора, расчётов и налогового учёта в соответствии с 152-ФЗ, на срок действия договора и 5 лет после его прекращения.</p>

<h4>8. Ответственность и приостановка</h4>
<p>8.1. Платформа вправе приостановить приём платежей при нарушении договора, правил Платформы или законодательства, уведомив Разработчика с указанием причины.</p>
<p>8.2. Платформа не отвечает за сбои агрегаторов и банков, но содействует их устранению.</p>

<h4>9. Срок, изменение, расторжение</h4>
<p>9.1. Договор действует бессрочно с момента акцепта. Акцептом является нажатие кнопки «Принимаю условия и отправляю анкету» в консоли; Платформа фиксирует время, IP-адрес, учётную запись и редакцию договора (ст. 438 ГК РФ).</p>
<p>9.2. Платформа может изменить условия, уведомив Разработчика в консоли не менее чем за 10 дней. Продолжение продаж после вступления изменений в силу означает согласие с ними.</p>
<p>9.3. Любая сторона может расторгнуть договор, уведомив другую за 10 дней.</p>

<h4>10. Реквизиты Платформы</h4>
<p>ИП Ливанов Александр Алексеевич · ИНН 771392840109 · ОГРНИП 326774600034839 · dustore.ru</p>
HTML;
}

function mon_offer_hash(string $type): string
{
    return hash('sha256', mon_offer_html($type));
}
